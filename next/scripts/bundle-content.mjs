// Copies the shared files (../activities, ../web) into lib/content.generated.ts at build time,
// so the same HTML files serve both the old Apps Script app and this one.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const files = {};
for (const dir of ['activities', 'web']) {
  for (const f of readdirSync(join(root, dir))) {
    if (/\.(html|js|json)$/.test(f)) files[`${dir}/${f}`] = readFileSync(join(root, dir, f), 'utf8');
  }
}
const out = '// Generated by scripts/bundle-content.mjs. Do not edit.\n' +
  'export const FILES: Record<string, string> = ' + JSON.stringify(files) + ';\n';
writeFileSync(join(here, '..', 'lib', 'content.generated.ts'), out);
console.log('Bundled ' + Object.keys(files).length + ' files.');
